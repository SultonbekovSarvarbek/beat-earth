export const DICTS: Record<Lang, Dict> = { ru, en, zh };
export type Key = Exclude<keyof Dict, "how">;

export function makeT(lang: Lang) {
  return (key: Key, vars: Record<string, string | number> = {}) => {
    let s = DICTS[lang][key] as string;
    for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
    return s;
  };
}

export function detectLang(): Lang {
  const saved = safeGet("be-lang");
  if (saved === "ru" || saved === "en" || saved === "zh") return saved;
  const l = (navigator.language || "en").toLowerCase();
  if (l.startsWith("zh")) return "zh";
  if (["ru", "uz", "kk", "ky", "tg", "be", "uk"].some((p) => l.startsWith(p))) return "ru";
  return "en";
}

export function locale(lang: Lang) {
  return lang === "zh" ? "zh-CN" : lang === "ru" ? "ru-RU" : "en-US";
}

export function safeGet(k: string) {
  try { return localStorage.getItem(k); } catch { return null; }
}
export function safeSet(k: string, v: string) {
  try { localStorage.setItem(k, v); } catch { /* storage unavailable */ }
}
